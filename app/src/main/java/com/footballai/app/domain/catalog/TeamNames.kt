/**
 * The naming dictionary: every team this app can name in Persian.
 *
 * Two kinds of names live here, with deliberately different standards.
 *
 * National teams are complete. Every team the results archive publishes has a
 * Persian name, taken from the standard Persian names of the countries (the ones a
 * Persian speaker would recognise, not transliterations typed as they were needed).
 * The ISO code is used to draw a flag without downloading anything.
 *
 * Clubs are a curated dictionary. A Persian name is only written down when it is the
 * name Persian football media actually use; a club that is not listed keeps its
 * published name. Nothing is transliterated on the fly, because a wrong name is worse
